import { Language } from './keyboard.types';

export type Difficulty = 'beginner' | 'intermediate' | 'advanced';

export type LessonCategory =
  | 'keys'
  | 'combinations'
  | 'words'
  | 'sentences'
  | 'paragraphs'
  | 'stories'
  | 'tests'
  | 'timed';

// Retain PracticeType as an alias for backwards compatibility
export type PracticeType = LessonCategory;

export interface LessonStep {
  keyCode: string; // e.g. "KeyK", "KeyD"
  modifiers?: ('Shift' | 'AltGr')[];
  expectedOutput: string; // Output generated by this keystroke
}

export interface TypingLesson {
  id: string;
  language: Language;
  title: string;
  category?: LessonCategory;
  practiceType?: PracticeType;
  difficulty: Difficulty;
  description?: string;
  content?: string[]; // Sequential passages queue
  targetText: string; // Active passage text
  steps: LessonStep[]; // Keystroke steps for active passage
  estimatedDuration?: number; // in seconds or minutes
  tags?: string[];
  order: number;
}
