import { Language } from './keyboard.types';

export type Difficulty = 'beginner' | 'intermediate' | 'advanced';

export type PracticeType = 'keys' | 'words' | 'sentences' | 'paragraphs' | 'timed';

export interface LessonStep {
  keyCode: string;          // e.g. "KeyK", "KeyD"
  modifiers?: ('Shift' | 'AltGr')[];
  expectedOutput: string;   // Output generated by this keystroke
}

export interface TypingLesson {
  id: string;
  language: Language;
  title: string;
  difficulty: Difficulty;
  practiceType: PracticeType;
  targetText: string;
  steps: LessonStep[];
  description?: string;
  order: number;
}
